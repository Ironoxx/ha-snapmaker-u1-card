// 2.4.0b3: the card's other languages as separate files, loaded on demand.
//
// German (source) and English (fallback) stay in the bundle. es/fr/it/nl/pt/tr/zh
// go to custom_components/.../frontend/i18n/<lang>.<hash>.json (+ .gz); the hash
// in the name lets Home Assistant's static path cache them for long and still
// deliver a changed table at once. frontend/src/i18n-files.gen.js tells the card
// the current file names. Runs before esbuild (npm run build); the output is
// deterministic, so the generated module can be committed.
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const zlib = require("zlib");

const SRC = path.join(__dirname, "../frontend/src/i18n");
const OUT = path.join(__dirname, "../custom_components/snapmaker_u1_card/frontend/i18n");
const GEN = path.join(__dirname, "../frontend/src/i18n-files.gen.js");

fs.mkdirSync(OUT, { recursive: true });
const files = {};
for (const name of fs.readdirSync(SRC).filter((f) => f.endsWith(".js")).sort()) {
  const lang = name.replace(/\.js$/, "");
  const text = fs.readFileSync(path.join(SRC, name), "utf8");
  // "export default { ... };" – the object literal only (plain data, no code)
  const table = new Function(`return (${text.slice(text.indexOf("{"), text.lastIndexOf("}") + 1)});`)();
  const json = JSON.stringify(table);
  const hash = crypto.createHash("sha256").update(json).digest("hex").slice(0, 8);
  const file = `${lang}.${hash}.json`;
  fs.writeFileSync(path.join(OUT, file), json);
  fs.writeFileSync(path.join(OUT, `${file}.gz`), zlib.gzipSync(json, { level: 9 }));
  files[lang] = file;
}
// drop tables of earlier builds
const keep = new Set(Object.values(files).flatMap((f) => [f, `${f}.gz`]));
for (const f of fs.readdirSync(OUT)) if (!keep.has(f)) fs.unlinkSync(path.join(OUT, f));
fs.writeFileSync(GEN, `// Generated by scripts/build-i18n.cjs (npm run build). Do not edit.\n`
  + `// File per language under /snapmaker_u1_card/card/i18n/, loaded on demand by i18n.js.\n`
  + `export const LANG_FILES = ${JSON.stringify(files, null, 2)};\n`);
console.log(`i18n: ${Object.keys(files).join(" ")}`);
